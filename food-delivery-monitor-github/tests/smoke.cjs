const fs=require('fs'),vm=require('vm'),assert=require('assert/strict'),path=require('path');
const root=path.resolve(__dirname,'..');
globalThis.FoodEngine=require(path.join(root,'src/engine.js'));
const M=require(path.join(root,'src/monthly.js'));
const data=FoodEngine.parse(fs.readFileSync(path.join(root,'data/demo.csv'),'utf8'));
assert.equal(data.issues.length,0);
assert.equal(data.orders.length,1212);
assert.deepEqual(['2024-01','2024-02','2024-03','2024-04'].map(month=>M.report(data,month).status),['baseline','stable','up','down']);
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.ok(html.includes('程序合成'));
assert.ok(!html.includes('C:\\Users\\'));
assert.ok(!html.includes('food_orders_new_delhi.csv'));
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,5);
const nodes=new Map();const ctx={document:{getElementById:id=>{if(!nodes.has(id))nodes.set(id,{value:id==='stability'?'5':'',textContent:''});return nodes.get(id);}}};
vm.createContext(ctx);scripts.forEach(m=>vm.runInContext(m[1],ctx));
vm.runInContext("render=()=>{};load(embeddedSample,'Synthetic demo')",ctx);
assert.equal(nodes.get('month').value,'2024-04');
assert.ok(vm.runInContext("monthlyMarkup('2024-04')",ctx).includes('订单金额下降'));
console.log('PASS: synthetic sample, four monthly states, standalone scripts, month selection and public data labels.');
